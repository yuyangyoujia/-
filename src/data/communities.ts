// 按省份分组
export function getCommunitiesByProvince(): Record<string, Community[]> {
  const grouped: Record<string, Community[]> = {}
  for (const c of communities) {
    if (!grouped[c.province]) grouped[c.province] = []
    grouped[c.province].push(c)
  }
  return grouped
}

// 获取所有城市
export function getUniqueCities(): string[] {
  return [...new Set(communities.map((c) => c.city))]
}

// 获取所有省份
export function getUniqueProvinces(): string[] {
  return [...new Set(communities.map((c) => c.province))]
}

// 获取所有类型
export function getUniqueTypes() {
  return [...new Set(communities.map((c) => c.type))]
}
